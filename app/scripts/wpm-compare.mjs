// Regenerates war3map.wpm of real maps with the app's own pathing code and compares it with the file the map has.
//
//   node scripts/wpm-compare.mjs [<map or folder>...] [--map <name>] [--cells N] [--save FILE] [--baseline FILE] [--jobs N]
//
// A map is unpacked with the release CLI (cached in the temp folder, keyed by the map's path, size and time), then
// buildPathingMap (src/builtin/terrain-viewer/pathmap.ts) runs on its terrain (war3map.w3e.txt) and doodads
// (war3map.doo.json) with the game's Terrain.slk/Water.slk and the map's own imports, as a save does. The result is
// diffed with the stored map/war3map.wpm cell by cell. No map is changed.
//
//   no argument      the smoketest_maps folder of the main checkout
//   <map or folder>  those maps instead (.w3x/.w3m; folders are searched, see find-maps.mjs); give the downloaded
//                    ladder folders here
//   --map NAME       only the maps whose file name contains NAME
//   --cells N        list N differing cells per map: x,y (tile, cell in tile) stored->regenerated bytes
//   --save FILE      write the per-map result as JSON (a baseline for a later run)
//   --baseline FILE  compare with a saved result: lists the maps that got better or worse; exit 1 if one got worse
//   --jobs N         maps at a time (default: up to 6)
//
// Needs the release CLI (`cargo build --release`, or W3PROJ_BIN) and the installed game (W3PROJ_GAME, .game-path).
// Not part of the app: a development tool, like twin-check.mjs.
import { execFileSync, spawn } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { availableParallelism, tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { gamePath, mainCheckout } from "../../tests/gamepath.mjs";
import { findMaps } from "./find-maps.mjs";

const app = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const exe = process.platform === "win32" ? ".exe" : "";
const bin = () => process.env.W3PROJ_BIN ?? join(mainCheckout(app), "target", "release", `w3proj${exe}`);

/** One map, in a child process: its regenerated wpm is written to `out`, the objects it couldn't find are printed. */
async function one(bundle, root, out, game, cli) {
  const { buildPathingMap, parseW3e, w3eFromText } = await import(pathToFileURL(bundle).href);
  const gameCat = (p) => execFileSync(cli, ["game", "--install", game, "cat", p.replace(/\\/g, "/")], { maxBuffer: 1 << 28, stdio: ["ignore", "pipe", "ignore"] });
  const walk = (d, sub = "") => readdirSync(d, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(join(d, e.name), `${sub}${e.name}/`) : [`${sub}${e.name}`]);
  const files = walk(root).map((path) => ({ path }));
  const w3 = {
    game: { readText: async (p) => gameCat(p).toString("utf8") },
    workspace: { files: () => files, readText: async (p) => readFileSync(join(root, p), "utf8"), project: () => ({ root }) },
    backend: { invoke: async (cmd, a) => { throw new Error(`no backend ${cmd} ${a?.path}`); } },
  };
  const read = async (p) => {
    const local = join(root, "map", p.replace(/\\/g, "/"));
    return existsSync(local) ? readFileSync(local) : gameCat(p);
  };
  const terrain = parseW3e(w3eFromText(readFileSync(join(root, "map", "war3map.w3e.txt"), "utf8")));
  const doodads = JSON.parse(readFileSync(join(root, "map", "war3map.doo.json"), "utf8")).doodads;
  const { wpm, missing, fellBack } = await buildPathingMap(w3, terrain, doodads, read);
  writeFileSync(out, wpm);
  console.log(JSON.stringify({ missing, fellBack }));
}

if (process.argv[2] === "--one") {
  const [, , , bundle, root, out, game, cli] = process.argv;
  await one(bundle, root, out, game, cli);
  process.exit(0);
}

// ---- parent ----
const args = process.argv.slice(2);
const opt = (name) => { const i = args.indexOf(name); if (i < 0) return null; const [, v] = args.splice(i, 2); return v ?? null; };
const only = opt("--map"), cellsN = Number(opt("--cells") ?? 0), saveTo = opt("--save"), baseFile = opt("--baseline");
const jobs = Number(opt("--jobs") ?? Math.min(6, availableParallelism()));
if (args.some((a) => a.startsWith("--"))) throw new Error(`unknown option ${args.find((a) => a.startsWith("--"))}`);

const cli = bin();
if (!existsSync(cli)) throw new Error(`${cli} not found: run cargo build --release first`);
const game = gamePath();
const given = args.length ? args : [join(mainCheckout(app), "smoketest_maps")];
let maps = findMaps(given.filter((p) => existsSync(p)));
given.filter((p) => !existsSync(p)).forEach((p) => console.log(`not found: ${p}`));
if (only) maps = maps.filter((m) => basename(m).includes(only));
if (!maps.length) throw new Error("no maps found (give a map or folder, or put maps into smoketest_maps)");

const cache = join(tmpdir(), "w3proj-wpm-compare");
mkdirSync(cache, { recursive: true });
const { build } = await import("esbuild");
const bundle = join(cache, `pathing-${process.pid}.mjs`);
await build({
  stdin: {
    contents: `export { buildPathingMap } from "./src/builtin/terrain-viewer/pathmap"; export { parseW3e } from "./src/lib/terrain/w3e"; export { w3eFromText } from "./src/lib/terrain/w3etext";`,
    resolveDir: app, loader: "ts",
  },
  bundle: true, format: "esm", platform: "node", outfile: bundle, logLevel: "warning",
});

const run = (file, argv) => new Promise((done) => {
  const child = spawn(file, argv, { stdio: ["ignore", "pipe", "pipe"] });
  let out = "", err = "";
  child.stdout.on("data", (d) => { out += d; });
  child.stderr.on("data", (d) => { err += d; });
  const timer = setTimeout(() => child.kill(), 300_000);
  child.on("error", (e) => { clearTimeout(timer); done({ code: -1, out, err: String(e) }); });
  child.on("close", (code) => { clearTimeout(timer); done({ code, out, err }); });
});

/** The map's unpacked project (reused while the map file is the same), or null with the reason. */
async function unpacked(map) {
  const st = statSync(map);
  const key = createHash("sha1").update(`${resolve(map)}|${st.size}|${st.mtimeMs}`).digest("hex").slice(0, 12);
  const dir = join(cache, `${basename(map).replace(/[^\w.()-]/g, "_")}-${key}`);
  const ready = join(dir, ".unpacked");
  if (!existsSync(ready)) {
    const r = await run(cli, ["unpack", map, dir, "--game", game]);
    if (r.code !== 0) return { why: `unpack failed: ${r.err.trim().split("\n").pop()}` };
    writeFileSync(ready, "");
  }
  const need = ["war3map.wpm", "war3map.w3e.txt", "war3map.doo.json"].filter((f) => !existsSync(join(dir, "map", f)));
  return need.length ? { why: `no ${need.join(", ")}` } : { dir };
}

const results = [];
async function compare(map) {
  // The folder too: the ladder seasons hold maps of the same name.
  const name = `${basename(dirname(resolve(map)))}/${basename(map)}`;
  const u = await unpacked(map);
  if (!u.dir) return { name, skip: u.why };
  const out = join(u.dir, "regenerated.wpm");
  const r = await run(process.execPath, [fileURLToPath(import.meta.url), "--one", bundle, u.dir, out, game, cli]);
  if (r.code !== 0) return { name, skip: `regeneration failed: ${(r.err || r.out).trim().split("\n").pop()}` };
  const old = readFileSync(join(u.dir, "map", "war3map.wpm")), neu = readFileSync(out);
  const w = old.readUInt32LE(8), h = old.readUInt32LE(12);
  if (neu.readUInt32LE(8) !== w || neu.readUInt32LE(12) !== h) return { name, skip: `size differs: stored ${w}x${h}, regenerated ${neu.readUInt32LE(8)}x${neu.readUInt32LE(12)}` };
  const cells = [];
  let diff = 0;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const a = old[16 + y * w + x], b = neu[16 + y * w + x];
    if (a === b) continue;
    diff++;
    if (cells.length < cellsN) cells.push(`  ${x},${y} (tile ${x >> 2},${y >> 2}, cell ${x & 3},${y & 3}) ${a.toString(16)}->${b.toString(16)}`);
  }
  return { name, total: w * h, diff, cells, ...JSON.parse(r.out.trim().split("\n").pop() || "{}") };
}

const queue = [...maps];
await Promise.all(Array.from({ length: Math.max(1, jobs) }, async () => {
  for (let m; (m = queue.shift()) !== undefined;) results.push(await compare(m));
}));
rmSync(bundle, { force: true });
results.sort((a, b) => a.name.localeCompare(b.name));

let exact = 0, diffCells = 0, compared = 0;
for (const r of results) {
  if (r.skip) { console.log(`${r.name}: skipped, ${r.skip}`); continue; }
  compared++;
  diffCells += r.diff;
  if (!r.diff) exact++;
  const extra = [r.missing?.length ? `missing ${r.missing.length}` : "", r.fellBack?.length ? `fell back ${r.fellBack.length}` : ""].filter(Boolean).join(", ");
  console.log(`${r.name}: ${r.diff ? `${r.diff} of ${r.total} cells differ` : "exact"}${extra ? ` (${extra})` : ""}`);
  for (const c of r.cells) console.log(c);
}
console.log(`total: ${exact} of ${compared} maps exact, ${diffCells} differing cells${results.length > compared ? `, ${results.length - compared} skipped` : ""}`);

const now = Object.fromEntries(results.filter((r) => !r.skip).map((r) => [r.name, r.diff]));
if (saveTo) {
  writeFileSync(saveTo, JSON.stringify({ maps: now }, null, 1) + "\n");
  console.log(`saved ${saveTo}`);
}
let worse = 0;
if (baseFile) {
  const base = JSON.parse(readFileSync(baseFile, "utf8")).maps;
  const better = [], worseList = [];
  for (const [name, n] of Object.entries(now)) {
    if (!(name in base) || base[name] === n) continue;
    (n < base[name] ? better : worseList).push(`  ${name}: ${base[name]} -> ${n}`);
  }
  worse = worseList.length;
  console.log(`against ${baseFile}: ${better.length} better, ${worse} worse, ${Object.keys(now).filter((n) => !(n in base)).length} not in the baseline`);
  if (better.length) console.log(`better:\n${better.join("\n")}`);
  if (worse) console.log(`worse:\n${worseList.join("\n")}`);
}
process.exit(worse ? 1 : 0);
