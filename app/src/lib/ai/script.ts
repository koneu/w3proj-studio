// The AI script (.ai) the World Editor's AI Editor exports for an AI file:
// a JASS script on top of common.ai with options, preset conditions, heroes and
// their skills, build/harvest priorities, attack groups, waves and targets.
// The layout follows the game's four exported scripts (Scripts/reforged_u05_navy.ai,
// reforged_u08_*.ai, next to their .wai), which were edited by hand afterwards
// ("Reforged revision"); parts they don't show (heroes, unit quantities other than
// "all", custom targets) are written the same way but aren't confirmed.

import { CONDITION, type TriggerData } from "../triggers/triggerdata";
import type { Param } from "../triggers/wtg";
import { NO_ID, type AiCall, type AiCondition, type AiFile } from "./wai";

const BAR = "//===========================================================================";
const STARS = "//***************************************************************************";
const HERO_IDS: Record<string, string> = { "1HIA": "hero_id", "2HIA": "hero_id2", "3HIA": "hero_id3" };
/** Hero training orders of the six chances (heroes 1, 2, 3). */
const ORDERS = [[0, 1, 2], [0, 2, 1], [1, 0, 2], [1, 2, 0], [2, 0, 1], [2, 1, 0]];

const signed = (n: number) => n | 0;
const quote = (id: string) => (HERO_IDS[id] ?? `'${id}'`);
const jassString = (s: string) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');

/** `gCond_<name>`: the global a named condition is kept in. */
export function conditionGlobal(name: string): string {
  return `gCond_${name.replace(/\W/g, "_")}`;
}

/** JASS for a condition function tree (TriggerData operators, AI functions). */
export function conditionJass(call: AiCall | { name: string; params: Param[] }, data: TriggerData, kind = CONDITION): string {
  const f = data.find(kind, call.name);
  const args = call.params.map((p, i) => paramJass(p, f?.args[i] ?? "", data));
  switch (call.name) {
    case "OperatorCompareInteger": case "OperatorCompareReal": case "OperatorCompareBoolean": case "OperatorInt": case "OperatorReal":
      return `( ${args[0]} ${args[1]} ${args[2]} )`;
    case "GetBooleanAnd": return `( ${args[0]} and ${args[1]} )`;
    case "GetBooleanOr": return `( ${args[0]} or ${args[1]} )`;
  }
  const name = f?.scriptName ?? call.name;
  return args.length ? `${name}( ${args.join(", ")} )` : `${name}()`;
}

function paramJass(p: Param, type: string, data: TriggerData): string {
  switch (p.type) {
    case 0: return data.presets.get(p.value)?.script ?? p.value;
    case 2: return p.call ? conditionJass(p.call, data, p.call.kind) : p.value;
    case 3: {
      if (/code$/.test(type)) return quote(p.value);
      if (type === "string" || type === "StringExt") return `"${jassString(p.value)}"`;
      return p.value;
    }
    default: return p.value;
  }
}

/** The script of `ai`. `date` goes into the header (the World Editor writes the export time). */
export function generateAiScript(ai: AiFile, data: TriggerData, date = new Date().toString()): string {
  const out: string[] = [];
  const add = (...lines: string[]) => out.push(...lines);
  const section = (title: string) => add(STARS, "//*", `//*  ${title}`, "//*", STARS, "");
  const fn = (comment: string | null, head: string, body: string[]) => {
    add(BAR);
    if (comment) add(`// ${comment}`, BAR);
    add(head, ...body, "endfunction", "");
  };
  const cond = (condIndex: number, c: AiCondition): string | null => {
    if (condIndex >= 0) {
      const named = ai.conditions.find((x) => x.index === condIndex);
      return named ? conditionGlobal(named.name) : null;
    }
    return condIndex === -2 && c.call ? conditionJass(c.call, data) : null;
  };
  /** Entries' lines, those with a condition inside `if (condition) then … endif`; neighbours
   *  with the same condition share one block. */
  const guardedRuns = (items: { c: string | null; lines: string[] }[], indent = "    "): string[] => {
    const lines: string[] = [];
    for (let i = 0; i < items.length;) {
      let j = i;
      while (j < items.length && items[j].c === items[i].c) j++;
      const run = items.slice(i, j).flatMap((x) => x.lines);
      lines.push(...(items[i].c ? [`${indent}if (${items[i].c}) then`, ...run.map((l) => `    ${l}`), `${indent}endif`] : run));
      i = j;
    }
    return lines;
  };
  const town = (t: number) => {
    const v = signed(t);
    return v >= 0 ? String(v) : v === -1 ? "-1" : v <= -3 ? (v === -3 ? "mine" : `mine + ${-3 - v}`) : String(v);
  };
  const on = (bit: number) => ((ai.options & bit) !== 0 ? "true" : "false");
  const [goldWorker, woodWorker, hall, mineBuilding] = ai.workers;

  // ---- header and globals ------------------------------------------------------------
  add(BAR, "// ", `// ${ai.name}`, "// ", "//   Warcraft III AI script", "//   Generated by the Warcraft III World Editor", `//   Date: ${date}`, "// ", BAR, "");
  section("Global Variables");
  add("globals",
    "    integer                 attackWave                 = 1",
    "    integer                 nextDelay                  = 0",
    "    integer                 awGold                     = 0",
    "    integer                 awWood                     = 0");
  if (ai.conditions.length) {
    add("", "    // Conditions");
    for (const c of ai.conditions) add(`    boolean                 ${conditionGlobal(c.name).padEnd(26)} = false`);
  }
  add("endglobals", "");

  // ---- utility functions -------------------------------------------------------------
  section("Utility Functions");
  fn(null, "function CheckLastCommand takes boolean pop returns integer",
    ["    local integer cmd = GetLastCommand()", "    if (pop) then", "        call PopLastCommand(  )", "    endif", "    return cmd"]);
  fn(null, "function CheckLastCommandData takes boolean pop returns integer",
    ["    local integer data = GetLastData()", "    if (pop) then", "        call PopLastCommand(  )", "    endif", "    return data"]);
  fn(null, "function TotalFoodProduced takes nothing returns integer", ["    return GetPlayerState(ai_player,PLAYER_STATE_RESOURCE_FOOD_CAP)"]);
  fn(null, "function ExpansionNeeded takes nothing returns boolean", ["    return take_exp"]);
  fn(null, "function BuildExpansion takes integer hallID, integer mineID returns nothing",
    ["    if (HallsCompleted(hallID)) then", "        call SetBuildExpa( TownCount(hallID) + 1, mineID )", "    endif"]);
  fn(null, "function CurrentAttackWave takes nothing returns integer", ["    return attackWave"]);
  fn(null, "function ResetAttackUnits takes nothing returns nothing", ["    set awGold = 0", "    set awWood = 0", "    call InitAssaultGroup(  )"]);
  fn(null, "function AddAttackUnit takes integer minQty, integer maxQty, integer unitID returns nothing", [
    "    // Track attacking gold workers", `    if (unitID == ${quote(goldWorker)}) then`, "        set awGold = awGold + minQty", "    endif", "",
    "    // Track attacking wood workers", `    if (unitID == ${quote(woodWorker)}) then`, "        set awWood = awWood + minQty", "    endif", "",
    "    call SetAssaultGroup( minQty, maxQty, unitID )"]);

  // ---- options -----------------------------------------------------------------------
  section("Basic Options");
  fn(null, "function InitOptions takes nothing returns nothing", [
    (ai.options & 0x1) ? "    call SetMeleeAI(  )" : "    call SetCampaignAI(  )",
    `    call SetDefendPlayer( ${on(0x8000)} )`,
    `    call SetRandomPaths( ${on(0x4000)} )`,
    `    call SetTargetHeroes( ${on(0x2)} )`,
    `    call SetPeonsRepair( ${on(0x4)} )`,
    `    call SetHeroesFlee( ${on(0x8)} )`,
    `    call SetHeroesBuyItems( ${on(0x10000)} )`,
    `    call SetUnitsFlee( ${on(0x10)} )`,
    `    call SetGroupsFlee( ${on(0x20)} )`,
    `    call SetWatchMegaTargets( ${on(0x40)} )`,
    `    call SetIgnoreInjured( ${on(0x80)} )`,
    `    call SetHeroesTakeItems( ${on(0x100)} )`,
    `    call SetSlowChopping( ${on(0x200)} )`,
    `    call SetCaptainChanges( ${on(0x400)} )`,
    `    call SetSmartArtillery( ${on(0x800)} )`,
    ...((ai.options & 0x2000) ? [`    call SetPlayerName( ai_player, "${jassString(ai.name)}" )`] : []),
  ]);

  // ---- conditions --------------------------------------------------------------------
  section("Conditions");
  fn("Updates the values of all preset conditions", "function UpdateConditions takes nothing returns nothing",
    ai.conditions.map((c) => `    set ${conditionGlobal(c.name)} = ${c.call ? conditionJass(c.call, data) : "false"}`));

  // ---- heroes ------------------------------------------------------------------------
  section("Heroes");
  const heroes = ai.heroes.map((h, i) => ({ id: h, i })).filter((h) => h.id !== NO_ID);
  const setHero: string[] = [];
  for (const [pos, slot] of [[0, ""], [1, "2"], [2, "3"]] as const) {
    if (!heroes.length) break;
    setHero.push(`    ${pos ? "elseif" : "if"} (order == ${pos + 1}) then`, `        set hero_id${slot} = heroid`);
    heroes.forEach((h, k) => {
      setHero.push(`        ${k ? "elseif" : "if"} (heroid == '${h.id}') then`);
      ai.skills[h.i * 3 + pos].forEach((s, level) => { if (s !== NO_ID) setHero.push(`            set skills${pos + 1}[${level + 1}] = '${s}'`); });
    });
    setHero.push("        endif");
  }
  if (setHero.length) setHero.push("    endif");
  fn("Stores hero ID and skills", "function SetHero takes integer order, integer heroid returns nothing", setHero);
  const select: string[] = ["    local integer roll = GetRandomInt(1,100)"];
  if (heroes.length) {
    let total = 0, first = true;
    ORDERS.forEach((order, k) => {
      const chance = ai.heroChances[k] ?? 0;
      if (chance <= 0) return;
      total += chance;
      select.push(`    ${first ? "if" : "elseif"} (roll <= ${total}) then`);
      first = false;
      order.forEach((h, pos) => { if (ai.heroes[h] !== NO_ID) select.push(`        call SetHero( ${pos + 1}, '${ai.heroes[h]}' )`); });
    });
    if (!first) select.push("    endif");
  }
  fn("Selects hero IDs for three possible heroes", "function SelectHeroes takes nothing returns nothing", select);
  fn("Returns the hero skill for the given hero and level", "function ChooseHeroSkill takes nothing returns integer", [
    "    local integer curHero = GetHeroId()", "    local integer level = GetHeroLevelAI()", "",
    "    if (level > max_hero_level) then", "        set max_hero_level = level", "    endif", "",
    "    if (curHero == hero_id) then", "        return skills1[level]", "    elseif (curHero == hero_id2) then", "        return skills2[level]",
    "    elseif (curHero == hero_id3) then", "        return skills3[level]", "    endif", "    return 0"]);

  // ---- building and harvesting -------------------------------------------------------
  section("Building and Harvesting");
  const totals = new Map<string, number>();
  const build: string[] = ["    local integer mine = TownWithMine()"];
  const buildItems: { c: string | null; lines: string[] }[] = [];
  for (const b of ai.build) {
    let line: string;
    if (b.kind === 2) line = `call BuildExpansion( ${quote(hall)}, ${quote(mineBuilding)} )`;
    else {
      const key = `${b.kind}:${b.id}`;
      const n = (totals.get(key) ?? 0) + 1;
      totals.set(key, n);
      line = `call SetBuildAll( ${b.kind === 1 ? "BUILD_UPGRADE" : "BUILD_UNIT"}, ${n}, ${quote(b.id)}, ${town(b.town)} )`;
    }
    buildItems.push({ c: cond(b.condIndex, b.cond), lines: [`    ${line}`] });
  }
  build.push(...guardedRuns(buildItems));
  fn("Specifies building priorities for workers", "function BuildPriorities takes nothing returns nothing", build);
  const harvest: string[] = ["    local integer mine = TownWithMine()",
    `    local integer allGold = GetUnitCountDone(${quote(goldWorker)})`, `    local integer allWood = GetUnitCountDone(${quote(woodWorker)})`, "    local integer numWorkers"];
  const harvestItems: { c: string | null; lines: string[] }[] = [];
  for (const b of ai.harvest) {
    const all = b.resource ? "allWood" : "allGold", attacking = b.resource ? "awWood" : "awGold";
    const w = signed(b.workers);
    const count = w === -1 ? all : w === -2 ? `${all} - ${attacking}` : String(b.workers);
    harvestItems.push({ c: cond(b.condIndex, b.cond),
      lines: [`    set numWorkers = ${count}`, `    call ${b.resource ? "HarvestWood" : "HarvestGold"}( ${town(b.town)}, numWorkers )`] });
  }
  harvest.push(...guardedRuns(harvestItems));
  fn("Specifies harvesting priorities for workers", "function HarvestPriorities takes nothing returns nothing", harvest);
  fn("Determines all building and harvesting assignments for workers", "function WorkerAssignment takes nothing returns nothing", [
    "    loop", "        call UpdateConditions(  )", "", "        // Harvesting", "        call ClearHarvestAI(  )", "        call HarvestPriorities(  )", "",
    "        // Building", "        call InitBuildArray(  )", "        call BuildPriorities(  )", "", "        call Sleep( 2 )", "    endloop"]);

  // ---- attacking ---------------------------------------------------------------------
  section("Attacking");
  // Groups are numbered in name order.
  const groups = [...ai.groups].sort((a, b) => a.name.localeCompare(b.name));
  const groupNo = (index: number) => groups.findIndex((g) => g.index === index) + 1;
  const isAll = (n: number) => signed(n) === -1;
  const min = ai.groups.find((g) => g.index === ai.minForces);
  const minimum: string[] = ["    local integer count", "", "    // Check for attack wave limit", `    if (attackWave > ${ai.waves.length}) then`, "        return false", "    endif", ""];
  let never = false;
  if (min) {
    minimum.push(`    // Attack Group: ${min.name}`);
    const fixed = min.units.filter((u) => !isAll(u.quantity));
    if (!min.units.length) {
      minimum.push("    // - No units in this attack group.  Never attack", "    return false");
      never = true;
    } else if (!fixed.length) {
      minimum.push("    // No specific minimums exist, checking for at least one unit", "    set count = 0",
        ...min.units.map((u) => `    set count = count + GetUnitCountDone(${quote(u.id)})`), "    if (count < 1) then", "        return false", "    endif");
    } else {
      minimum.push(...guardedRuns(fixed.map((u) => ({ c: cond(u.condIndex, u.cond),
        lines: [`    if (GetUnitCountDone(${quote(u.id)}) < ${u.quantity}) then`, "        return false", "    endif"] }))));
    }
  }
  if (!never) minimum.push("    return true");
  fn("Returns true if the minimum forces for an attack exist", "function HaveMinimumAttackers takes nothing returns boolean", minimum);
  const prepare: string[] = ["    local integer all", ""];
  groups.forEach((g, k) => {
    // Later groups' comments sit inside the previous branch.
    prepare.push(`${k ? "        " : "    "}// Attack Group #${k + 1}: ${g.name}`, `    ${k ? "elseif" : "if"} (groupID == ${k + 1}) then`);
    const unitItems: { c: string | null; lines: string[] }[] = [];
    for (const u of g.units) {
      const id = quote(u.id);
      const lines = isAll(u.quantity)
        ? [`set all = GetUnitCountDone( ${id} )`, `call AddAttackUnit( all, all, ${id} )`]
        : isAll(u.max)
          ? [`set all = GetUnitCountDone( ${id} )`, `call AddAttackUnit( ${u.quantity}, all, ${id} )`]
          : [`call AddAttackUnit( ${u.quantity}, ${u.max}, ${id} )`];
      unitItems.push({ c: cond(u.condIndex, u.cond), lines: lines.map((l) => `        ${l}`) });
    }
    prepare.push(...guardedRuns(unitItems, "        "));
    prepare.push("");
  });
  if (groups.length) prepare.push("    endif");
  fn("Assigns units to attack based on the given attack group", "function PrepareAttackGroup takes integer groupID returns nothing", prepare);
  const forces: string[] = [];
  ai.waves.forEach((w, k) => forces.push(`    ${k ? "elseif" : "if"} (attackWave == ${k + 1}) then`, `        call PrepareAttackGroup( ${groupNo(w.group)} )`));
  if (ai.waves.length) forces.push("    endif");
  fn("Prepares an attack group based on the current attack wave", "function PrepareForces takes nothing returns nothing", forces);
  const waveDelays: [number, number][] = [[0, ai.initialDelay], ...ai.waves.map((w, k): [number, number] => [k + 1, w.delay])];
  const delays = waveDelays.filter(([, d]) => d > 0);
  const delay = ["    if (inWave < nextDelay) then", "        return", "    endif", ""];
  if (delays.length) {
    delays.forEach(([wave, d], k) => delay.push(`    ${k ? "elseif" : "if"} (inWave == ${wave}) then`, `        call Sleep( ${d} )`));
    delay.push("    endif", "");
  }
  delay.push("    set nextDelay = inWave + 1");
  fn("Sleep delays for each attack wave", "function AttackWaveDelay takes integer inWave returns nothing", delay);
  const update = ["    call AttackWaveDelay( attackWave )", "    set attackWave = attackWave + 1"];
  if (ai.repeatWaves > 0 && ai.waves.length) {
    update.push(`    if (attackWave > ${ai.waves.length}) then`, `        set attackWave = ${Math.max(1, ai.waves.length - ai.repeatWaves + 1)}`,
      "        set nextDelay = attackWave + 1", "    endif");
  }
  fn("Advances attack wave counter", "function AttackWaveUpdate takes nothing returns nothing", update);
  fn("Basic attack functionality", "function AttackTarget takes unit target, boolean addAlliance returns nothing", [
    "    if (target == null) then", "        return", "    endif", "    if (addAlliance) then", "        call SetAllianceTarget( target )", "    endif",
    "    call FormGroup( 3, true )", "    call AttackMoveKillA( target )", "    if (not addAlliance) then", "        call SetAllianceTarget( null )", "    endif"]);
  const launch = ["    local unit target = null", "    local boolean setAlly = true", "", "    // Don't launch any attack while town is threatened",
    "    if (TownThreatened()) then", "        call Sleep( 2 )", "        return", "    endif", ""];
  ai.targets.forEach((t, k) => {
    const c = cond(t.condIndex, t.cond);
    launch.push(`    // Target Priority #${k + 1}`, `    if (target == null${c ? ` and ${c}` : ""}) then`);
    switch (t.target) {
      case 0: launch.push("        set target = GetAllianceTarget()", "        if (target != null) then", "            set setAlly = false", "        endif"); break;
      case 1: launch.push("        set target = GetExpansionFoe()", "        if (target != null) then", "            set take_exp = false", "        endif"); break;
      case 2: launch.push("        set target = GetMegaTarget()"); break;
      case 3: launch.push("        set target = GetEnemyExpansion()"); break;
      case 4: launch.push("        set target = GetEnemyExpansion()", "        if (target == null) then", "            call StartGetEnemyBase(  )", "            loop",
        "                exitwhen (not WaitGetEnemyBase())", "                call SuicideSleep( 1 )", "            endloop", "            set target = GetEnemyBase()", "        endif"); break;
      case 5: launch.push(`        set target = GetCreepCamp( ${t.creep?.min ?? 0}, ${t.creep?.max ?? 100}, ${t.creep?.allowFlyers ? "true" : "false"} )`); break;
      case 6: launch.push("        call PurchaseZeppelin(  )"); break;
    }
    launch.push("    endif", "");
  });
  launch.push("    // Attack the target and increment attack wave", "    if (target != null) then", "        call AttackTarget( target, setAlly )", "        call AttackWaveUpdate(  )",
    "    else", "        // If no target was found, sleep a bit before trying again", "        call Sleep( 20 )", "    endif");
  fn("Initiates an attack based on target priorities", "function LaunchAttack takes nothing returns nothing", launch);
  fn("Determines all attacking assignments", "function AttackAssignment takes nothing returns nothing", [
    "    call StaggerSleep( 0, 2 )", "    if (attackWave == 1) then", "        call AttackWaveDelay( 0 )", "    endif", "    loop", "        loop",
    "            call UpdateConditions(  )", "            exitwhen (HaveMinimumAttackers() and not CaptainRetreating())", "            call Sleep( 2 )", "        endloop",
    ...((ai.options & 0x1000) ? ["        call RemoveInjuries(  )"] : []),
    "        call ResetAttackUnits(  )", "        call PrepareForces(  )", "        call LaunchAttack(  )", "    endloop"]);

  // ---- main --------------------------------------------------------------------------
  section("Main Entry Point");
  fn(null, "function main takes nothing returns nothing", [
    "    call InitAI(  )", "    call InitOptions(  )", "    call SelectHeroes(  )", "    call CreateCaptains(  )", "    call SetHeroLevels( function ChooseHeroSkill )", "",
    "    call Sleep( 0.1 )", "    call StartThread( function WorkerAssignment )", "    call StartThread( function AttackAssignment )", "    call PlayGame(  )"]);
  // The file ends with an empty line.
  return [...out, ""].join("\r\n");
}
